use crate::save_sync::{
    ensure_no_reparse_components, hold_save_directory_chain, resolve_retrobat_paths,
};
use anyhow::Context;
use quick_xml::events::{BytesStart, Event};
use quick_xml::{Reader, Writer};
use std::fs;
use std::path::Path;

const SETTING: &str = "switch.yuzu_mutualize";

/// Target the frontend's system option, which both verified launchers consume.
/// Preserve unrelated XML/events and reject per-game settings that undo it.
pub fn switch_save_setting(xml: &str) -> anyhow::Result<String> {
    super::xml::validate_document(xml, "config")?;
    let mut reader = Reader::from_str(xml);
    let mut writer = Writer::new(Vec::new());
    let mut found = false;
    let mut root_seen = false;
    loop {
        let event = reader
            .read_event()
            .context("invalid RetroBat settings XML")?;
        match event {
            Event::DocType(_) => anyhow::bail!("RetroBat settings cannot contain a document type"),
            Event::Start(ref element) | Event::Empty(ref element) => {
                let mut name = None;
                let mut value = None;
                for attribute in element.attributes() {
                    let attribute = attribute?;
                    let decoded = attribute
                        .normalized_value(quick_xml::XmlVersion::default())?
                        .into_owned();
                    match attribute.key.as_ref() {
                        b"name" => name = Some(decoded),
                        b"value" => value = Some(decoded),
                        _ => {}
                    }
                }
                if let Some(name) = name {
                    anyhow::ensure!(!(name.starts_with("switch[") && name.ends_with(".yuzu_mutualize") && value.as_deref() != Some("true")),
                        "per-game RetroBat override {name:?} changes the save destination; configuration was preserved");
                    if name == SETTING {
                        anyhow::ensure!(
                            element.name().as_ref() == b"bool",
                            "Switch save setting is not a boolean"
                        );
                        anyhow::ensure!(!found, "duplicate Switch save setting");
                        found = true;
                        let mut replacement = element.to_owned();
                        replacement.clear_attributes();
                        for attribute in element.attributes() {
                            let attribute = attribute?;
                            if attribute.key.as_ref() != b"value" {
                                replacement.push_attribute(attribute);
                            }
                        }
                        replacement.push_attribute(("value", "true"));
                        writer.write_event(if matches!(event, Event::Empty(_)) {
                            Event::Empty(replacement)
                        } else {
                            Event::Start(replacement)
                        })?;
                        continue;
                    }
                }
                if element.name().as_ref() == b"config" {
                    anyhow::ensure!(!root_seen, "duplicate RetroBat config root");
                    root_seen = true;
                    if matches!(event, Event::Empty(_)) {
                        writer.write_event(Event::Start(element.to_owned()))?;
                        write_setting(&mut writer)?;
                        writer.write_event(Event::End(element.to_end()))?;
                        found = true;
                        continue;
                    }
                }
            }
            Event::End(ref element) if element.name().as_ref() == b"config" && !found => {
                write_setting(&mut writer)?;
                found = true;
            }
            Event::Eof => break,
            _ => {}
        }
        writer.write_event(event)?;
    }
    anyhow::ensure!(root_seen && found, "missing RetroBat config root");
    Ok(String::from_utf8(writer.into_inner())?)
}

fn write_setting(writer: &mut Writer<Vec<u8>>) -> anyhow::Result<()> {
    let mut element = BytesStart::new("bool");
    element.push_attribute(("name", SETTING));
    element.push_attribute(("value", "true"));
    writer.write_event(Event::Empty(element))?;
    Ok(())
}

/// Back up and publish the one targeted frontend setting while stopped. Emulator
/// INI files are generated by RetroBat, not patched with guessed cross-emulator
/// keys. The caller must establish frontend/emulator inactivity first.
pub fn configure_switch_saves(installation: &Path) -> anyhow::Result<Vec<String>> {
    let (home, saves) = resolve_retrobat_paths(installation)?;
    let path = home.join("es_settings.cfg");
    ensure_no_reparse_components(&path)?;
    let _guard = hold_save_directory_chain(&home)?;
    let before = fs::read_to_string(&path)?;
    let after = switch_save_setting(&before)?;
    if after != before {
        let backup = home.join(format!(
            "es_settings.cfg.rommfs-{}.bak",
            uuid::Uuid::new_v4()
        ));
        let mut file = std::fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(backup)?;
        std::io::Write::write_all(&mut file, before.as_bytes())?;
        file.sync_all()?;
        let mut staged = tempfile::NamedTempFile::new_in(&home)?;
        std::io::Write::write_all(staged.as_file_mut(), after.as_bytes())?;
        staged.as_file().sync_all()?;
        ensure_no_reparse_components(&path)?;
        anyhow::ensure!(
            fs::read_to_string(&path)? == before,
            "RetroBat settings changed during setup; retry with RetroBat stopped"
        );
        staged.persist(&path).map_err(|error| error.error)?;
    }
    let mut messages = vec![format!(
        "Switch saves resolve to {}",
        saves.join("switch").display()
    )];
    for emulator in ["eden", "citron"] {
        let executable = installation
            .join("emulators")
            .join(emulator)
            .join(format!("{emulator}.exe"));
        ensure_no_reparse_components(&executable)?;
        if !executable.is_file() {
            messages.push(format!("{emulator} is not installed; its save setting is configured for future launcher use"));
        }
    }
    Ok(messages)
}
